const CATEGORY_EN_MAP: Record<string, string> = {
  'perlindungan & tauhid': 'Protection & Tauhid',
  'syukur & tawakal': 'Gratitude & Trust',
  'akidah & niat': 'Creed & Intention',
  'ibadah & zikir': 'Worship & Dhikr',
  'akhlak & adab': 'Character & Etiquette',
};

export function translateCategoryName(
  name: string | undefined,
  lang: Language,
  nameEn?: string
): string {
  if (!name) return '';
  if (lang !== 'en') return name;
  if (nameEn && nameEn.trim()) return nameEn.trim();
  return CATEGORY_EN_MAP[name.trim().toLowerCase()] ?? name;
}

export function translateDalilStatus(status: string | undefined, lang: Language): string {
  if (!status) return '';
  if (lang !== 'en') return status;
  return status
    .replace(/Al-Quran Al-Karim/gi, 'The Noble Quran')
    .replace(/Al-Quran & Hadis Shahih/gi, 'Al-Quran & Authentic Hadith')
    .replace(/Nash Qath['’]i/gi, 'Definitive Scriptural Text')
    .replace(/Shahih · Muttafaqun ['’]Alaih/gi, "Sahih · Muttafaqun 'Alayh")
    .replace(/Muttafaqun ['’]Alaih \(Shahih Bukhari & Muslim\)/gi, "Muttafaqun 'Alayh (Bukhari & Muslim)")
    .replace(/Muttafaqun ['’]Alaih/gi, "Muttafaqun 'Alayh")
    .replace(/Hasan Shahih/gi, 'Hasan Sahih')
    .replace(/Dinilai Hasan/gi, 'Graded Hasan')
    .replace(/Dishahihkan/gi, 'Authenticated')
    .replace(/oleh Syaikh/gi, 'by Shaykh')
    .replace(/oleh /gi, 'by ')
    .replace(/Hadis Shahih/gi, 'Authentic Hadith')
    .replace(/Wajib \/ Rukun/gi, 'Obligatory / Pillar')
    .replace(/Sunnah Muakkadah/gi, 'Confirmed Sunnah')
    .replace(/\bShahih\b/g, 'Sahih')
    .replace(/\batau\b/gi, 'or');
}

export function translateDalilSource(source: string | undefined, lang: Language): string {
  if (!source) return '';
  if (lang !== 'en') return source;
  return source
    .replace(/\bHR\.\s*/g, 'Narrated by ')
    .replace(/\bQS\.\s*/g, 'Quran ')
    .replace(/Kaidah Hijab Faraid \(Ijma['’]\)/gi, "Faraid Exclusion Rule (Ijma')")
    .replace(/Kaidah Hijab & Ashabah Faraid/gi, 'Faraid Exclusion & Residuary Rules')
    .replace(/Kesepakatan Ulama Ahli Sunnah/gi, 'Consensus of Ahlus Sunnah Scholars')
    .replace(/\bShahih\b/g, 'Sahih')
    .replace(/\bKitab\b/gi, 'Book')
    .replace(/\bayat\b/gi, 'verse(s)')
    .replace(/\bdalam\b/gi, 'in')
    .replace(/\bdari\b/gi, 'from')
    .replace(/\bdan\b/gi, 'and')
    .replace(/\batau\b/gi, 'or');
}


